import { test, expect } from '@playwright/test'
import { spawn } from 'node:child_process'
import { readFile, mkdir, mkdtemp } from 'node:fs/promises'
import path from 'node:path'

let server, dataRoot, password, setupKey
const errors = []
test.describe.configure({ mode: 'serial' })

test.beforeAll(async ({ request }) => {
  const temp = path.resolve('../.tools/tmp')
  await mkdir(temp, { recursive: true })
  dataRoot = await mkdtemp(path.join(temp, 'browser-'))
  password = 'Browser-test-password-2026'
  const binary = path.resolve(process.env.CABBAGE_TEST_BINARY || '../dist/cabbage-windows-amd64.exe')
  const args = ['--addr', '127.0.0.1:15700', '--data', dataRoot]
  if (process.env.CABBAGE_TEST_WEB_DIR) {
    const webDir = process.env.CABBAGE_TEST_WEB_DIR
    args.push('--web', path.isAbsolute(webDir) ? webDir : path.resolve('..', webDir))
  }
  server = spawn(binary, args, { windowsHide: true, stdio: 'ignore' })
  await expect.poll(async () => { try { return (await request.get('/healthz')).status() } catch { return 0 } }, { timeout: 15000 }).toBe(200)
  setupKey = (await readFile(path.join(dataRoot, 'setup.key'), 'utf8')).trim()
})

test.afterAll(async () => {
  if (server && !server.killed) server.kill()
})

