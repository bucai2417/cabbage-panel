test('sorting and pinning: tasks and environment variables', async ({ page }) => {
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('用户名', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '进入工作空间' }).click()
  await page.getByRole('button', { name: '定时任务', exact: true }).click()
  for (const name of ['排序旧任务', '排序新任务']) {
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    await page.getByLabel('任务名称').fill(name)
    await page.getByLabel('执行命令', { exact: true }).fill('echo ' + name)
    await page.getByLabel('Cron 表达式', { exact: true }).fill('')
    await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  }
  const taskNames = page.locator('.task-row .task-name-button strong')
  await expect(taskNames.filter({ hasText: '排序新任务' })).toBeVisible()
  let order = await taskNames.allTextContents()
  expect(order.indexOf('排序新任务')).toBeLessThan(order.indexOf('排序旧任务'))
  await page.getByRole('switch', { name: '启用排序旧任务' }).click()
  await expect(page.getByRole('switch', { name: '启用排序旧任务' })).toHaveAttribute('aria-checked', 'false')
  order = await taskNames.allTextContents()
  expect(order.indexOf('排序旧任务')).toBeGreaterThan(order.indexOf('排序新任务'))
  await page.getByRole('button', { name: '置顶排序旧任务', exact: true }).click()
  order = await taskNames.allTextContents()
  expect(order.indexOf('排序旧任务')).toBeGreaterThan(order.indexOf('排序新任务'))
  await page.getByRole('switch', { name: '启用排序旧任务' }).click()
  await expect(page.getByRole('switch', { name: '启用排序旧任务' })).toHaveAttribute('aria-checked', 'true')
  order = await taskNames.allTextContents()
  expect(order.indexOf('排序旧任务')).toBeLessThan(order.indexOf('排序新任务'))
  await page.getByRole('button', { name: '环境变量', exact: true }).click()
  await page.getByLabel('筛选环境变量').selectOption('disabled')
  await expect(page.getByText('BROWSER_TEST', { exact: true })).toBeVisible()
  await page.getByLabel('筛选环境变量').selectOption('enabled')
  await expect(page.getByText('BROWSER_TEST', { exact: true })).toHaveCount(0)
  await page.getByLabel('筛选环境变量').selectOption('all')
  await page.getByRole('button', { name: '置顶BROWSER_TEST', exact: true }).click()
  await page.getByLabel('筛选环境变量').selectOption('pinned')
  await expect(page.getByText('BROWSER_TEST', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
